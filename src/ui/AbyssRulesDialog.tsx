export function AbyssRulesDialog({ onClose }: { readonly onClose: () => void }) {
  const [active, setActive] = useState(sections[0]!.id);
  const section = sections.find(item => item.id === active)!;
  return <AbyssDialog title="深渊 · 规则讲解" className="abyss-dialog--traits abyss-dialog--rules" onClose={onClose}>
    <nav className="abyss-rules__tabs" aria-label="规则章节">{sections.map(item => <button type="button" key={item.id}
      aria-pressed={active === item.id} onClick={() => setActive(item.id)}>{item.title}</button>)}</nav>
    <article className="abyss-rules__page"><h3>{section.title}</h3>
      {section.paragraphs.map((paragraph, index) => <p key={index}>{paragraph}</p>)}
      {active === 'rarity' && <div className="abyss-rules__rarities" aria-label="JSON稀有度表">{rarityList.filter(item => !item.isEvent)
        .slice().sort((a, b) => b.level - a.level).map(item => <span key={item.rarity} style={{ color: item.color }}>
          <strong>{item.rarity}</strong><small>level {item.level}</small>
        </span>)}</div>}
      {active === 'boons' && <div className="abyss-grade-legend">{ABYSS_GRADES.map(grade => <span key={grade}
        style={{ color: ABYSS_GRADE_INFO[grade].color }}>◆ {ABYSS_GRADE_INFO[grade].name}</span>)}</div>}
    </article>
  </AbyssDialog>;
}
