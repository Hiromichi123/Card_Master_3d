import { NearestFilter, RepeatWrapping, SRGBColorSpace, TextureLoader, type Texture } from 'three';
import manifest from '../../data/surfaceTextures.json';

const files: Readonly<Record<string, string>> = manifest;
const loader = new TextureLoader();
const pendingClones = new WeakMap<Texture, Set<Texture>>();

/** A clone shares the decoded image, but its upload version must advance when that image arrives. */
export function cloneSurfaceTexture(source: Texture): Texture {
  const clone = source.clone();
  const waiting = pendingClones.get(source);
  if (waiting) {
    waiting.add(clone);
    clone.addEventListener('dispose', () => waiting.delete(clone));
  }
  return clone;
}

/** Generated by scripts/bake-surfaces.mjs from the same procedural functions, without resampling. */
export function bakedSurfaceTexture(key: string): Texture | undefined {
  const file = files[key];
  if (!file) return undefined;
  const waiting = new Set<Texture>();
  const texture: Texture = loader.load(`${import.meta.env.BASE_URL}assets/surfaces/${file}`, () => {
    for (const clone of waiting) clone.needsUpdate = true;
    waiting.clear(); pendingClones.delete(texture);
  }, undefined, () => { waiting.clear(); pendingClones.delete(texture); });
  // Valid neutral pixels while disk decoding finishes; no incomplete texture warnings/flashing black.
  const neutral = key.startsWith('normal:') ? [128, 128, 255, 255]
    : key.startsWith('rough:') ? [128, 128, 128, 255] : [255, 255, 255, 255];
  // WebGL2 immutable storage is allocated on first upload, including the mip chain.
  // A 1x1 placeholder cannot later accept a 512/768px image without recreating it.
  // Keep final dimensions from the manifest key so all live UV clones stay valid.
  const size = Number(key.split(':')[1]);
  const pixels = new Uint8ClampedArray(size * size * 4);
  const pixel = new Uint32Array(new Uint8Array(neutral).buffer)[0]!;
  new Uint32Array(pixels.buffer).fill(pixel);
  texture.image = new ImageData(pixels, size, size);
  texture.needsUpdate = true;
  pendingClones.set(texture, waiting);
  texture.wrapS = texture.wrapT = RepeatWrapping;
  texture.anisotropy = key.startsWith('normal:') ? 1 : 8;
  texture.flipY = !key.startsWith('normal:');
  if (key.startsWith('normal:')) {
    // The generator used DataTexture's nearest filtering and no mipmaps for these normals.
    texture.minFilter = texture.magFilter = NearestFilter;
    texture.generateMipmaps = false;
  }
  if (key.startsWith('wood:') || key.startsWith('marble:')) texture.colorSpace = SRGBColorSpace;
  return texture;
}
