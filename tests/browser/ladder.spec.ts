import { expect, test } from '@playwright/test';
import { collectProblems, openWithFreshSave, readProfile } from './helpers';

test('天梯双入口与专用卡组往返，匹配暂未开放', async ({ page }) => {
  const problems = collectProblems(page);
  await openWithFreshSave(page);
  await page.locator('.menu__columns').getByRole('button', { name: '进入战斗', exact: true }).click();
  await page.locator('.menu__columns').getByRole('button', { name: '天梯赛', exact: true }).click();
  await expect(page.locator('.ladder__header h1')).toHaveText('天梯赛');
  await expect(page.locator('.ladder__match[data-mode="solo"]')).toBeDisabled();
  await expect(page.locator('.ladder__match[data-mode="duo"]')).toBeDisabled();
  await expect(page.locator('.ladder__new')).toHaveText('NEW');
  await expect(page.getByRole('progressbar', { name: '天梯段位进度' })).toHaveAttribute('aria-valuenow', '0');
  await expect(page.locator('.ladder__rank')).toHaveText('新手卡牌师');
  await expect(page.locator('.ladder__card')).toHaveCount(12);
  await expect(page.locator('.ladder__rank-step [data-tier-logo]')).toHaveCount(9);
  await expect(page.locator('.ladder__match .ladder__score')).toHaveCount(0);
  const beforeReward = await readProfile(page);
  await page.locator('.ladder__rank-step[data-floor="0"] button').click();
  await expect(page.locator('.ladder__rank-step[data-floor="0"] button')).toHaveText('已领取');
  const afterReward = await readProfile(page);
  expect(afterReward!.currencies.crystal).toBe(beforeReward!.currencies.crystal + 100);
  expect(afterReward!.ladder.claimedTierFloors).toEqual([0]);
  await page.locator('.ladder__ranking button').click();
  await expect(page.getByRole('dialog')).toContainText('本地演示');
  await expect(page.getByRole('dialog').locator('tbody tr')).toHaveCount(21);
  await page.getByRole('tab', { name: '收藏榜', exact: true }).click();
  await expect(page.getByRole('dialog').locator('tbody tr')).toHaveCount(21);
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.locator('.ladder__configure').click();
  await expect(page.getByRole('tab')).toHaveCount(4);
  await expect(page.getByRole('tab', { name: '天梯赛卡组', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: '清空卡组', exact: true }).click();
  await page.getByRole('button', { name: '返回天梯赛', exact: true }).click();
  await expect(page.locator('.ladder__strength strong')).toHaveText('未配置');
  const saved = await readProfile(page);
  expect(saved?.decks.find(deck => deck.id === saved.ladder.deckId)?.cardIds).toEqual([]);
  expect(saved?.decks.find(deck => deck.id === saved.activeDeckId)?.cardIds.length).toBe(12);
  await page.getByRole('button', { name: '活动大厅', exact: true }).click();
  await page.locator('.activity-wheel__option', { hasText: '天梯赛' }).click();
  await page.locator('.activity-detail__enter').click();
  await expect(page.locator('.ladder__header h1')).toHaveText('天梯赛');
  await expect(page.locator('.ladder__strength strong')).toHaveText('未配置');
  await page.locator('.ladder__configure').click();
  await page.getByRole('button', { name: '前往对战模式', exact: true }).click();
  await expect(page.locator('.menu__title')).toHaveText('选择对战模式');
  await page.locator('.app-nav').getByRole('button', { name: '配置', exact: true }).click();
  await expect(page.getByRole('tab', { name: '天梯赛卡组', exact: true })).toHaveAttribute('aria-selected', 'false');
  await expect(page.getByRole('tab', { name: /卡组1/ })).toHaveAttribute('aria-selected', 'true');
  expect(problems).toEqual([]);
});
